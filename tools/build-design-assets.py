def build_icon_paths(phosphor_dir):
    lines = [
        "// <auto-generated> por tools/build-design-assets.py: no editar a mano. </auto-generated>",
        "// Íconos: Phosphor Icons (https://phosphoricons.com), licencia MIT (assets/Phosphor-LICENSE.txt).",
        # Partido para que REUSE no lo tome como la licencia de este script.
        "// SPDX-" "FileCopyrightText: 2023 Phosphor Icons",
        "// SPDX-" "License-Identifier: MIT",
        "",
        "namespace Kumquat.Design;",
        "",
        "/// <summary>Trazados SVG (viewBox 0 0 256 256, relleno) de los íconos de Kumquat.</summary>",
        "public static partial class IconPaths",
        "{",
        "    private static readonly System.Collections.Generic.Dictionary<string, string> Data = new(System.StringComparer.Ordinal)",
        "    {",
    ]
    for name, source in sorted(ICONS.items()):
        with open(os.path.join(phosphor_dir, source + ".svg"), encoding="utf-8") as f:
            svg = f.read()
        paths = re.findall(r'<path[^>]* d="([^"]+)"', svg)
        if not paths:
            raise SystemExit(f"Sin trazado: {source}")
        lines.append(f'        ["{name}"] = "{" ".join(paths)}",')
    lines += ["    };", "}", ""]
    out = os.path.join(REPO, "src", "Kumquat.Design", "IconPaths.g.cs")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("íconos:", len(ICONS), "->", out)


def build_ico():
    source = os.path.join(REPO, "assets", "logo", "kumquat.png")
    sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    images = []
    with tempfile.TemporaryDirectory() as tmp:
        for size in sizes:
            png = os.path.join(tmp, f"{size}.png")
            # Cuadrado con márgenes transparentes, escalado de alta calidad conservando el alfa.
            vf = f"scale={size}:{size}:force_original_aspect_ratio=decrease:flags=lanczos,format=rgba,pad={size}:{size}:(ow-iw)/2:(oh-ih)/2:color=0x00000000"
            subprocess.run([FFMPEG, "-loglevel", "error", "-y", "-i", source, "-vf", vf, "-frames:v", "1", "-update", "1", png], check=True)
            with open(png, "rb") as f:
                images.append((size, f.read()))
    header = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    entries = b""
    body = b""
    for size, data in images:
        dim = 0 if size >= 256 else size
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset + len(body))
        body += data
    out = os.path.join(REPO, "assets", "logo", "kumquat.ico")
    with open(out, "wb") as f:
        f.write(header + entries + body)
    print("ico:", sizes, "->", out)


