"""
Genera src/Kumquat.Core/Localization/Strings.g.cs desde Strings.resx (español, el idioma base):
  - un texto sin {0} es una propiedad:            Strings.CopyPath
  - un texto con {0}, {1}… es un método; los nombres de los parámetros salen del comentario de
    la clave ("params: count, target"):           Strings.ConvertedTo(count, target)
Uso: python tools/build-strings.py
Los demás idiomas (Strings.<idioma>.resx) no generan código; LocalizationTests verifica que
tengan las mismas claves y los mismos {n}.
"""
import os
import re
import xml.etree.ElementTree as ET

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FOLDER = os.path.join(REPO, "src", "Kumquat.Core", "Localization")
PLACEHOLDER = re.compile(r"\{(\d+)(?:[,:][^}]*)?\}")


def entries(path):
    root = ET.parse(path).getroot()
    for data in root.findall("data"):
        value = data.findtext("value") or ""
        comment = data.findtext("comment") or ""
        yield data.get("name"), value, comment


def doc(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")


def main():
    lines = [
        "// <auto-generated> por tools/build-strings.py desde Strings.resx: no editar a mano. </auto-generated>",
        "// SPDX-" "License-Identifier: GPL-3.0-or-later",
        "",
        "#nullable enable",
        "",
        "namespace Kumquat.Core.Localization;",
        "",
        "public static partial class Strings",
        "{",
    ]
    seen = set()
    for name, value, comment in entries(os.path.join(FOLDER, "Strings.resx")):
        if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name):
            raise SystemExit(f"Clave inválida (PascalCase): {name}")
        if name in seen:
            raise SystemExit(f"Clave repetida: {name}")
        seen.add(name)
        count = len({int(m) for m in PLACEHOLDER.findall(value)})
        lines.append(f"    /// <summary>{doc(value)}</summary>")
        if count == 0:
            lines.append(f'    public static string {name} => Get("{name}");')
        else:
            match = re.search(r"params:\s*([\w ,]+)", comment)
            if not match:
                raise SystemExit(f"{name} tiene {count} parámetros: falta 'params: …' en el comentario")
            params = [p.strip() for p in match.group(1).split(",")]
            if len(params) != count:
                raise SystemExit(f"{name}: {count} parámetros en el texto y {len(params)} en el comentario")
            signature = ", ".join(f"object? {p}" for p in params)
            lines.append(f'    public static string {name}({signature}) => Format("{name}", {", ".join(params)});')
        lines.append("")
    lines[-1] = "}"
    lines.append("")
    out = os.path.join(FOLDER, "Strings.g.cs")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("textos:", len(seen), "->", out)


if __name__ == "__main__":
    main()
